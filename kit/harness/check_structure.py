#!/usr/bin/env python3
"""check_structure.py — fast, offline lint for Harbor task packages.

Catches the structural, config, and hygiene problems that would otherwise waste a container build or ship a
leaky package. It does NOT run tests (that's selfcheck.sh); it only reads files.

Usage:
    harness/check_structure.py path/to/<instance_id> [more ...]
    harness/check_structure.py path/to/generated_tasks/*

Exit code 0 if every task passes, 1 otherwise.
"""
from __future__ import annotations
import json, os, re, sys, tomllib

# The full task structure Harbor 0.25.0 needs to build + grade. `tests/test.sh` is the verifier ENTRY
# (Harbor runs it; without it 0.25.0 won't even recognize the folder as a task). A grader (grade.py|grade.sh)
# is checked separately below. These 11 + the grader = the 12 required files of the interface contract.
REQUIRED_FILES = [
    "task.toml", "instruction.md",
    "solution/solve.sh", "solution/patch.diff",
    "tests/test.sh", "tests/run_script.sh", "tests/parser.py",
    "tests/fail_to_pass.json", "tests/pass_to_pass.json", "tests/test_patch.diff",
    "environment/Dockerfile",
]
VALID_NETWORK = {"no-network", "allowlist", "public"}
EXT_LANG = {".py": "python", ".js": "javascript", ".ts": "javascript", ".tsx": "javascript",
            ".cpp": "cpp", ".cc": "cpp", ".cxx": "cpp", ".h": "cpp", ".hpp": "cpp"}
# Hygiene: generated packages must not leak authoring/AI tells or personal identity.
TELL_RE = re.compile(r"\b(as an ai|language model|chatgpt|openai|i apologize|i cannot assist|"
                     r"generated by (an )?ai)\b", re.I)
EMAIL_RE = re.compile(r"[A-Za-z0-9._%+-]+@(gmail|yahoo|outlook|hotmail|proton)\.[A-Za-z]{2,}", re.I)


def added_paths(diff_path):
    """Files a unified diff touches (b/ side)."""
    paths = set()
    if not os.path.isfile(diff_path):
        return paths
    for ln in open(diff_path, encoding="utf-8", errors="replace"):
        m = re.match(r"^\+\+\+ b/(.+)$", ln.strip())
        if m:
            paths.add(m.group(1).strip())
    return paths


def check(task):
    iid = os.path.basename(task.rstrip("/"))
    errs, warns = [], []

    # 1. required files
    for rel in REQUIRED_FILES:
        if not os.path.isfile(os.path.join(task, rel)):
            errs.append(f"missing {rel}")
    # a grader must exist under tests/
    if not any(os.path.isfile(os.path.join(task, "tests", g)) for g in ("grade.py", "grade.sh")):
        errs.append("missing tests/grade.py (or grade.sh)")

    # 2. task.toml schema
    tt = os.path.join(task, "task.toml")
    meta = env = {}
    if os.path.isfile(tt):
        try:
            cfg = tomllib.load(open(tt, "rb"))
            meta = cfg.get("metadata", {}); env = cfg.get("environment", {})
            if meta.get("instance_id") and meta["instance_id"] != iid:
                warns.append(f"metadata.instance_id ({meta['instance_id']}) != folder name ({iid})")
            if meta.get("name") and meta["name"] != meta.get("instance_id", iid):
                warns.append(f"metadata.name should equal instance_id (got {meta['name']!r})")
            if not meta.get("base_commit") or not re.fullmatch(r"[0-9a-f]{40}", str(meta.get("base_commit",""))):
                errs.append("metadata.base_commit missing or not a 40-char sha")
            nm = env.get("network_mode")
            if nm is not None and nm not in VALID_NETWORK:
                errs.append(f'environment.network_mode="{nm}" invalid (use {sorted(VALID_NETWORK)})')
            di = (env.get("docker_image") or "").strip()
            if di and not re.search(r"(docker\.io/|ghcr\.io/|quay\.io/|public\.ecr|/library/)", di):
                errs.append(f'environment.docker_image="{di}" looks private/local — leave it "" so Harbor builds the Dockerfile')
        except Exception as e:
            errs.append(f"task.toml not parseable: {e}")

    # 3. gold and test patch must not edit the same file
    gold = added_paths(os.path.join(task, "solution", "patch.diff"))
    testp = added_paths(os.path.join(task, "tests", "test_patch.diff"))
    shared = gold & testp
    if shared:
        errs.append(f"gold and test patch edit the same file(s): {sorted(shared)} "
                    f"(gold gets reverted on test-path reset)")

    # 4. language 3-way consistency (toml vs gold patch extensions)
    plang = (meta.get("programming_language") or "").lower()
    exts = {}
    for p in gold:
        _, e = os.path.splitext(p)
        if e in EXT_LANG:
            exts[EXT_LANG[e]] = exts.get(EXT_LANG[e], 0) + 1
    if plang and exts:
        dom = max(exts, key=exts.get)
        if dom != plang:
            warns.append(f"programming_language={plang} but gold patch is mostly {dom}")

    # 5. f2p / p2p sanity
    for name in ("fail_to_pass", "pass_to_pass"):
        p = os.path.join(task, "tests", f"{name}.json")
        if os.path.isfile(p):
            try:
                d = json.load(open(p))
                if not isinstance(d, list) or not d:
                    errs.append(f"tests/{name}.json must be a non-empty JSON array")
            except Exception as e:
                errs.append(f"tests/{name}.json not valid JSON: {e}")

    # 6. hygiene: no AI/authoring tells or personal emails in participant-facing text
    for rel in ("instruction.md", "task.toml"):
        fp = os.path.join(task, rel)
        if os.path.isfile(fp):
            txt = open(fp, encoding="utf-8", errors="replace").read()
            if TELL_RE.search(txt):
                errs.append(f"{rel} contains an AI/authoring tell")
            if EMAIL_RE.search(txt):
                errs.append(f"{rel} contains a personal email address")

    # 7. junk
    for dp, _, files in os.walk(task):
        if os.path.basename(dp) in ("__pycache__", "node_modules", ".git"):
            warns.append(f"junk dir shipped: {os.path.relpath(dp, task)}")
        for f in files:
            if f.endswith((".pyc", ".bak", ".orig")) or f == ".DS_Store":
                warns.append(f"junk file shipped: {os.path.relpath(os.path.join(dp, f), task)}")

    return errs, warns


def main(argv):
    if len(argv) < 2:
        print("usage: check_structure.py <task_dir> [<task_dir> ...]", file=sys.stderr)
        return 2
    bad = 0
    for task in argv[1:]:
        iid = os.path.basename(task.rstrip("/"))
        errs, warns = check(task)
        if errs:
            bad = 1
            print(f"✗ {iid}")
            for e in errs: print(f"    ERROR  {e}")
            for w in warns: print(f"    warn   {w}")
        else:
            print(f"✓ {iid}" + (f"  ({len(warns)} warning(s))" if warns else ""))
            for w in warns: print(f"    warn   {w}")
    return bad


if __name__ == "__main__":
    sys.exit(main(sys.argv))
